EditType = Literal["move", "add", "remove", "resize", "degrid"]


class EditOperation(BaseModel):
    """A typed edit instruction produced by Critic VLM."""

    type: EditType = Field(
        ...,
        description="Closed edit vocabulary: move | add | remove | resize | degrid",
    )
    targets: List[str] = Field(
        default_factory=list,
        description="Target instance IDs to edit",
    )
    hint: str = Field(
        ...,
        description="Concise spatial instruction for refinement operator Psi",
    )


class CriticScores(BaseModel):
    """Quantitative evaluation scores computed in Critic stage."""

    s_c: float = Field(
        ...,
        description="Normalized count score: max(0, 1 - |c_hat - c_gt| / c_gt)",
    )
    detected_count: int = Field(..., alias="c_hat", description="Detected instance count c_hat")
    target_count: int = Field(..., alias="N", description="Target count N (c_gt)")
    s_a: float = Field(..., description="Aesthetic score in [0, 1] from aesthetic estimator")
    C_acc: float = Field(default=0.0, description="Count accuracy measure")
    S: float = Field(
        ...,
        description="Composite score: S = alpha * s_c + (1 - alpha) * s_a",
    )
    alpha: float = Field(default=0.6, description="Count weight alpha (fixed to 0.6)")

    model_config = {"populate_by_name": True}


class CriticFeedback(BaseModel):
    """Structured critique produced by Critic VLM."""

    scores: CriticScores
    decision: Dict[str, Any] = Field(
        default_factory=lambda: {"continue": True, "reason": "refining"},
        description="Advisory decision dictionary ('continue', 'reason')",
    )
    feedback: Dict[str, Any] = Field(
        ...,
        description="Feedback containing summary, count evaluation, and typed edits list",
    )

    @property
    def edits(self) -> List[EditOperation]:
        """Extracts list of EditOperation models from feedback."""
        raw_edits = self.feedback.get("edits", [])
        parsed = []
        for item in raw_edits:
            if isinstance(item, EditOperation):
                parsed.append(item)
            elif isinstance(item, dict):
                parsed.append(EditOperation.model_validate(item))
        return parsed


class IterationRecord(BaseModel):
    """Snapshot of a single refinement iteration."""

    round_idx: int
    scores: CriticScores
    planning_graph: PlanningGraph
    critic_feedback: CriticFeedback
    reasoning_trace: Optional[str] = None
    image_path: Optional[str] = None
    elapsed_time_sec: float = 0.0


class GenerationResult(BaseModel):
    """Final output bundle from CountLoopPipeline."""

    prompt: str
    target_count: int
    final_count: int
    composite_score: float
    converged: bool
    iterations_run: int
    final_image_path: str
    planning_graph: PlanningGraph
    history: List[IterationRecord]
    total_elapsed_sec: float
